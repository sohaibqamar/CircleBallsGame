# Run this in NORMAL PowerShell (no admin) before npm run android:
#   . .\scripts\use-android-sdk.ps1
#
# Sets Android SDK for THIS terminal session only (no IT / env GUI needed).

# Uses ANDROID_HOME if already set, otherwise Android Studio's default location.
$SdkRoot = if ($env:ANDROID_HOME) { $env:ANDROID_HOME } else { Join-Path $env:LOCALAPPDATA "Android\Sdk" }

if (-not (Test-Path "$SdkRoot\platform-tools\adb.exe")) {
  Write-Host "ERROR: Android SDK not found at:" -ForegroundColor Red
  Write-Host "  $SdkRoot"
  Write-Host ""
  Write-Host "Check where Android Studio installed the SDK (SDK Manager), then edit SdkRoot in this script."
  return
}

$env:ANDROID_HOME = $SdkRoot
$env:ANDROID_SDK_ROOT = $SdkRoot

$platformTools = "$SdkRoot\platform-tools"
$emulator = "$SdkRoot\emulator"
foreach ($dir in @($platformTools, $emulator)) {
  if ($env:Path -notlike "*$dir*") {
    $env:Path = "$dir;$env:Path"
  }
}

# Gradle reads this file (android/local.properties is gitignored)
$localProps = Join-Path $PSScriptRoot "..\android\local.properties"
$sdkDirForGradle = $SdkRoot -replace '\\', '/'
@"
## Generated by scripts/use-android-sdk.ps1 - machine-local, do not commit
sdk.dir=$sdkDirForGradle
"@ | Set-Content -Path $localProps -Encoding ASCII

Write-Host "Android SDK ready for this session:" -ForegroundColor Green
Write-Host "  ANDROID_HOME = $env:ANDROID_HOME"
& "$SdkRoot\platform-tools\adb.exe" version
